import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL,fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
if(!process.argv[2]||!process.argv[3])throw Error('Pass Playwright module and Chromium executable paths.');
const {chromium,expect}=await import(pathToFileURL(process.argv[2]).href);
const {url}=JSON.parse(await readFile(new URL('../artifacts/preview.json',import.meta.url)));
const browser=await chromium.launch({headless:true,executablePath:process.argv[3]});
try{
  const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`${url}/directions/index.html`);
  const current = page.locator('#scene > :not(.scene-outgoing)');
  const settle = () => page.evaluate(async()=>{await Promise.all(document.getAnimations().map(animation=>animation.finished.catch(()=>{})));});
  const select = async (scope,name,option) => {
    await scope.getByRole('combobox',{name,exact:true}).click();
    await page.getByRole('option',{name:option,exact:true}).click();
  };
  const checkInputFocus = async input => {
    await input.evaluate(node=>node.blur());
    const border = await input.evaluate(node=>getComputedStyle(node).borderColor);
    await input.focus();
    assert.deepEqual(await input.evaluate(node=>({outline:getComputedStyle(node).outlineStyle,shadow:getComputedStyle(node).boxShadow,border:getComputedStyle(node).borderColor})),{outline:'none',shadow:'none',border});
  };
  await page.evaluate(async()=>{await document.fonts.ready;await document.fonts.load('500 14px MiSans');});
  assert.equal(await page.evaluate(()=>document.fonts.check('14px MiSans','收藏音乐Lemon')),true);
  assert.deepEqual(await page.evaluate(()=>[...document.fonts].map(font=>font.status)),['loaded','loaded']);
  assert.equal(await page.title(),'DiscAtelier');
  await expect(current.locator('.record-caption h1')).toHaveText('location');
  await page.getByRole('button',{name:'选择 Lemon',exact:true}).click();
  await expect(current.locator('.record-caption h1')).toHaveText('Lemon');
  await page.evaluate(async()=>{await Promise.all([...document.images].map(image=>image.decode()));await Promise.all(document.getAnimations().map(animation=>animation.finished.catch(()=>{})));});
  await page.screenshot({path:fileURLToPath(new URL('../artifacts/store-minimal.png',import.meta.url)),fullPage:true});
  await page.getByRole('button',{name:'搜索收藏',exact:true}).click();
  await checkInputFocus(page.locator('#search'));
  await page.getByRole('searchbox',{name:'搜索关键词'}).fill('Lemon');
  await expect(current.locator('.record-sleeve')).toHaveCount(1);
  await page.keyboard.press('Escape');
  await expect(page.locator('#search')).not.toBeVisible();
  await page.getByRole('button',{name:'更多',exact:true}).click();
  await select(page,'收藏范围','想购入');
  await expect(page.locator('.empty-state')).toBeVisible();
  await page.getByRole('button',{name:'更多',exact:true}).click();
  await select(page,'收藏范围','全部');
  await page.getByRole('button',{name:'取出 Lemon',exact:true}).click();
  await page.getByRole('button',{name:'购入',exact:true}).click();
  await checkInputFocus(page.locator('#purchase-tab [name="amount"]'));
  await select(page.locator('#purchase-tab'),'币种','HKD');
  await page.locator('#purchase-tab').getByRole('combobox',{name:'币种',exact:true}).focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Home');
  await page.keyboard.press('Enter');
  await expect(page.locator('#purchase-tab [name="currency"]')).toHaveValue('CNY');
  await page.locator('#purchase-tab').getByRole('combobox',{name:'收藏状态',exact:true}).click();
  await settle();
  await page.screenshot({path:fileURLToPath(new URL('../artifacts/custom-controls.png',import.meta.url)),fullPage:true});
  await page.keyboard.press('Escape');
  await expect(page.locator('#inspection')).toBeVisible();
  await expect(page.locator('.select-list:popover-open')).toHaveCount(0);
  await page.locator('#purchase-tab [name="amount"]').fill('99.90');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await expect(page.locator('#metadata')).toContainText('99.90');
  await page.keyboard.press('Escape');
  await expect(page.locator('#inspection')).not.toBeVisible();
  await page.getByRole('button',{name:'更多',exact:true}).click();
  await expect(page.locator('#amount')).toContainText('99.90');
  await page.locator('#organize').click();
  await expect(current.locator('tbody tr')).toHaveCount(8);
  await page.getByRole('button',{name:'更多',exact:true}).click();
  await page.locator('#organize').click();
  await current.locator('.record-sleeve[data-current="true"]').focus();
  await page.keyboard.press('ArrowRight');
  await expect(current.locator('.record-caption h1')).toHaveText('MOON BABY');
  await page.getByRole('button',{name:'添加收藏',exact:true}).click();
  const add = page.locator('#add-form');
  await checkInputFocus(add.locator('[name="title"]'));
  await select(add,'状态','在途');
  await select(add,'分区','影像');
  await add.locator('[name="title"]').fill('界面验证');
  await add.getByRole('button',{name:'加入收藏',exact:true}).click();
  await expect(page.locator('#add-dialog')).not.toBeVisible();
  await expect(current.locator('.record-caption h1')).toHaveText('界面验证');
  await page.getByRole('button',{name:'添加收藏',exact:true}).click();
  await expect(add.getByRole('combobox',{name:'状态',exact:true})).toHaveText('已购入');
  await expect(add.getByRole('combobox',{name:'分区',exact:true})).toHaveText('影像');
  await page.keyboard.press('Escape');
  await expect(page.locator('#add-dialog')).not.toBeVisible();
  await page.getByRole('button',{name:'音乐',exact:true}).click();
  await page.setViewportSize({width:980,height:800});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.emulateMedia({reducedMotion:'reduce'});
  await current.locator('.record-sleeve[data-current="true"]').click();
  await page.keyboard.press('Escape');
  await expect(page.locator('#inspection')).not.toBeVisible();
  assert.deepEqual(errors,[]);
  const result={checks:['MiSans font loading','input focus without highlight','custom selects and keyboard navigation','nested Escape','form reset synchronization','album selection','search','filter menu','purchase and totals','organizer','keyboard browsing','manual add','compact viewport','reduced motion'],pageErrors:errors};
  await writeFile(new URL('../artifacts/directions-results.json',import.meta.url),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
}finally{await browser.close();}
